const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listItems: () => ipcRenderer.invoke('items:list'),
  saveItem: (item) => ipcRenderer.invoke('items:save', item),
  deleteItem: (id) => ipcRenderer.invoke('items:delete', id),
  discardCovers: (names) => ipcRenderer.invoke('cover:discard', names),
  searchRemote: (params) => ipcRenderer.invoke('search:remote', params),
  fetchTracks: (params) => ipcRenderer.invoke('lookup:tracks', params),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (s) => ipcRenderer.invoke('settings:set', s),
  settingsStatus: () => ipcRenderer.invoke('settings:status'),
  openDiscogsTokenPage: () => ipcRenderer.invoke('open:discogsTokenPage'),
  pickCover: () => ipcRenderer.invoke('cover:pick'),
  phoneInfo: () => ipcRenderer.invoke('phone:info'),
  phoneStop: () => ipcRenderer.invoke('phone:stop'),
  exportBackup: () => ipcRenderer.invoke('backup:export'),
  coverOrphans: () => ipcRenderer.invoke('covers:orphans'),
  coverCleanup: () => ipcRenderer.invoke('covers:cleanup'),
  exportExcel: () => ipcRenderer.invoke('export:excel'),
  importBackup: () => ipcRenderer.invoke('backup:import'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  prefsSet: (p) => ipcRenderer.invoke('prefs:set', p),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateOpen: (url) => ipcRenderer.invoke('update:open', url),
  updateSkip: (v) => ipcRenderer.invoke('update:skip', v),
  onUpdateAvailable: (cb) => ipcRenderer.on('update-available', (ev, data) => cb(data)),
  importDiscogsApi: () => ipcRenderer.invoke('import:discogsApi'),
  importDiscogsCsv: () => ipcRenderer.invoke('import:discogsCsv'),
  onImportProgress: (cb) => ipcRenderer.on('import-progress', (ev, data) => cb(data)),
  onPhoneEvent: (cb) => ipcRenderer.on('phone-event', (ev, data) => cb(data)),
  onDataChanged: (cb) => ipcRenderer.on('data-changed', (ev, data) => cb(data || {}))
});
